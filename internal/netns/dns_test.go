// The default resolver does not understand the messages: it forwards them to the first of the
// machine's servers that answers, which covers every record type and a VPN's internal names.
func TestResolverForwardsToTheFirstServerThatAnswers(t *testing.T) {
	t.Parallel()
	dead := netip.MustParseAddrPort("127.0.0.1:1")
	server, asked := dnsServer(t)

	resolve := forwardTo([]netip.AddrPort{dead, server})
	answer, err := resolve(context.Background(), []byte("a query"))
	if err != nil {
		t.Fatalf("the resolver gave up: %v", err)
	}
	if string(answer) != "an answer" {
		t.Errorf("answer = %q", answer)
	}
	if got := <-asked; string(got) != "a query" {
		t.Errorf("the server received %q, want the query as is", got)
	}

	// Without a server, it says so rather than waiting.
	if _, err := forwardTo(nil)(context.Background(), []byte("x")); err == nil {
		t.Error("without a DNS server, the resolution should fail")
	}
	if _, err := forwardTo([]netip.AddrPort{dead})(context.Background(), []byte("x")); err == nil {
		t.Error("an unreachable server should return an error")
	}
}

// Port 53 is served over both transports: over UDP the message is bare, over TCP it is preceded by
// its length — a resolver that ignores it breaks every large answer.
func TestServeDNSSpeaksBothTransports(t *testing.T) {
	t.Parallel()
	resolve := func(context.Context, []byte) ([]byte, error) { return []byte("answer"), nil }

	t.Run("udp", func(t *testing.T) {
		t.Parallel()
		client, app := net.Pipe()
		go serveDNS(app, false, resolve, func(string) {})
		defer client.Close()

		client.Write([]byte("question"))
		got := read(t, client, len("answer"))
		if string(got) != "answer" {
			t.Errorf("answer = %q, want it bare", got)
		}
	})

	t.Run("tcp", func(t *testing.T) {
		t.Parallel()
		client, app := net.Pipe()
		go serveDNS(app, true, resolve, func(string) {})
		defer client.Close()

		client.Write([]byte{0, 8})
		client.Write([]byte("question"))
		got := read(t, client, 2+len("answer"))
		if want := []byte{0, byte(len("answer"))}; string(got[:2]) != string(want) {
			t.Errorf("announced length = %v, want %v", got[:2], want)
		}
		if string(got[2:]) != "answer" {
			t.Errorf("answer = %q", got[2:])
		}
	})
}

// A failing resolution shows in the network's log, without bringing the conversation down.
func TestServeDNSTellsWhenItCannotResolve(t *testing.T) {
	t.Parallel()
	client, app := net.Pipe()
	said := make(chan string, 4)
	go serveDNS(app, false, func(context.Context, []byte) ([]byte, error) {
		return nil, errors.New("no server")
	}, func(line string) { said <- line })
	defer client.Close()

	client.Write([]byte("question"))
	select {
	case line := <-said:
		if !strings.Contains(line, "no server") {
			t.Errorf("log = %q, want the reason", line)
		}
	case <-time.After(2 * time.Second):
		t.Error("the resolution failure said nothing")
	}
}

func TestNameserversAreReadFromResolvConf(t *testing.T) {
	t.Parallel()
	got := parseNameservers([]byte(`# generated by the machine
search corp.example
nameserver 127.0.0.53
nameserver 2001:db8::1
options edns0 trust-ad
nameserver not-an-address
`))
	want := []string{"127.0.0.53:53", "[2001:db8::1]:53"}
	if len(got) != 2 || got[0].String() != want[0] || got[1].String() != want[1] {
		t.Errorf("servers = %v, want %v", got, want)
	}
}

// The DNS address must be that of no interface of the private network: otherwise the query would be
// delivered on the spot instead of going up into the TUN.
func TestResolverAddrIsNobodysAddress(t *testing.T) {
	t.Parallel()
	for subnet, want := range map[string]string{
		"10.77.0.0/24":     "10.77.0.254",
		"192.168.240.0/29": "192.168.240.6",
		"172.20.0.0/16":    "172.20.255.254",
	} {
		v := &Virtual{subnet: netip.MustParsePrefix(subnet)}
		if got := v.resolverAddr().String(); got != want {
			t.Errorf("DNS of %s = %s, want %s", subnet, got, want)
		}
		if v.resolverAddr() == v.gateway() {
			t.Errorf("%s: the DNS and the way out share an address", subnet)
		}
	}
}

// dnsServer sets up a fake DNS server and returns its address, plus the channel where it tells what
// it was asked.
func dnsServer(t *testing.T) (netip.AddrPort, chan []byte) {
	t.Helper()
	conn, err := net.ListenUDP("udp", &net.UDPAddr{IP: net.IPv4(127, 0, 0, 1)})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { conn.Close() })
	asked := make(chan []byte, 1)
	go func() {
		buf := make([]byte, 512)
		n, from, err := conn.ReadFromUDP(buf)
		if err != nil {
			return
		}
		asked <- append([]byte(nil), buf[:n]...)
		conn.WriteToUDP([]byte("an answer"), from)
	}()
	return conn.LocalAddr().(*net.UDPAddr).AddrPort(), asked
}

func read(t *testing.T, conn net.Conn, size int) []byte {
	t.Helper()
	conn.SetReadDeadline(time.Now().Add(2 * time.Second))
	buf := make([]byte, size)
	n, err := conn.Read(buf)
	if err != nil {
		t.Fatalf("nothing to read: %v", err)
	}
	return buf[:n]
}
